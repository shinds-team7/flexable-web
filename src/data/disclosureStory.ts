/** 마지막 글자에 받침이 있으면 a, 없으면 b. %는 "퍼센트"로 읽어 받침 없음, 한글이 아니면 받침 없음으로 본다 */
function josa(word: string, a: string, b: string) {
  const t = word.replace(/['")\]\s]+$/, '');
  const c = t.charCodeAt(t.length - 1) - 0xac00;
  return c >= 0 && c <= 11171 && c % 28 !== 0 ? a : b;
}
